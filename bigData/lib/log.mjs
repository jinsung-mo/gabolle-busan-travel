/**
 * 스크립트가 사람에게 말하는 한 가지 방법.
 *
 * ── 🔴 왜 만들었나 ───────────────────────────────────────────────────────
 *
 * 같은 도우미가 **30벌 복사**돼 있었고, 그중 **시각 형식이 두 갈래**로 갈려 있었다
 * (2026-09-18 실측).
 *
 *     15개 파일   slice(11, 19)  →  05:46:34
 *     12개 파일   slice(0, 19)   →  2026-09-18T00:15:39
 *     그 밖에     export 판 1 · QUIET 판 1 · 형식 없는 판 1
 *
 * 같은 저장소의 스크립트가 시각을 두 가지로 찍고 있었다. 로그를 나란히 놓고 보는
 * 사람에게는 그게 **다른 팀이 짠 것처럼** 보인다.
 *
 * 🔴 **지우는 것이 아니라 모으는 일이다.** 이 출력들은 디버그 찌꺼기가 아니라
 *    수집·산출 스크립트의 **진행 보고**이고, 그건 그 프로그램의 정상 기능이다.
 *    없애면 「몇 건 넣었는지」를 아무도 못 보게 된다.
 *
 * ── 형식을 `시:분:초` 로 고른 이유 ───────────────────────────────────────
 *
 * 다수(15 대 12)를 따랐다. 그리고 이 스크립트들은 **한 번에 몇 분짜리**라 날짜가
 * 줄마다 반복될 이유가 없다. 날짜는 실행 지문(`mlops/manifest.mjs`)이 남긴다.
 *
 * ── 쓰는 법 ──────────────────────────────────────────────────────────────
 *
 *     import { log, die } from '../lib/log.mjs'
 *
 *     log('가로수 레코드 835건')            // 05:46:34 가로수 레코드 835건
 *     die(2, '🔴 입력 없음: ...')           // stderr 로 내고 종료 코드 2
 *
 * 🔴 `die` 는 **stderr** 로 낸다. 진행 보고(stdout)와 섞이면 `> out.log` 로 받았을 때
 *    실패가 성공 줄 사이에 묻힌다. 종료 코드가 진짜 판정이지만, 사람이 읽을 때도
 *    갈려 있어야 한다.
 */

let quiet = false

/** 진행 보고를 끈다. 되돌리려면 `setQuiet(false)`. */
export function setQuiet(on) {
  quiet = Boolean(on)
}

/** 지금 조용한가. */
export function isQuiet() {
  return quiet
}

const stamp = () => new Date().toISOString().slice(11, 19)

/**
 * 진행 보고. stdout 으로 나간다.
 *
 * 🔴 조용히 하기로 했으면 아무것도 안 낸다 — 호출하는 쪽이 `if` 를 쓰지 않게.
 */
export const log = (...a) => {
  if (!quiet) console.log(stamp(), ...a)
}

/**
 * 멈춘다. **`setQuiet` 과 무관하게 언제나 낸다** — 조용히 죽는 것이 제일 나쁘다.
 *
 * @param {number} code 종료 코드. 0 은 쓰지 않는다 — `die` 는 실패를 뜻한다
 * @param {...any} msg 사람이 읽을 이유. 무엇을 해야 하는지까지 적는다
 */
export const die = (code, ...msg) => {
  console.error(stamp(), ...msg)
  process.exit(code)
}
