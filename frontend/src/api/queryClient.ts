// 서버에서 받아온 데이터를 화면 밖에 보관한다 — S15P21E201-957.
//
// 왜 필요한가. 탭은 router.replace 로 이동하므로 앞 화면이 언마운트되고, 그 화면이
// useState 에 들고 있던 데이터가 함께 사라진다. 그래서 같은 탭에 다시 들어갈 때마다
// 서버를 또 불렀다(2026-09-15 운영 실측: /trips 재방문 시 GET /api/v1/trips 재발생).
//
// 보관소를 화면 밖에 두면 화면이 사라져도 데이터는 남는다. 다시 들어가면 그 값을
// 즉시 그리고, 낡았을 때만 조용히 다시 불러온다.
import { QueryClient } from '@tanstack/react-query';

/**
 * 🔴 기본값을 일부러 보수적으로 잡았다.
 *
 * <p>{@code staleTime} 30초 — 이 시간 안에는 다시 안 묻는다. 탭을 오가는 동안
 * 서버를 때리지 않게 하는 것이 이 티켓의 목적이고, 30초면 그 왕복은 덮으면서도
 * "한참 전 값을 계속 본다" 는 느낌은 안 준다.
 *
 * <p>{@code gcTime} 5분 — 화면을 떠난 뒤 값을 얼마나 들고 있을지. 짧으면 탭을
 * 오가는 사이에 버려져서 캐시가 없는 것과 같아진다.
 *
 * <p>재시도 1회 — 기본값 3회는 서버가 죽었을 때 사용자를 오래 기다리게 한다.
 * 이 앱은 실패를 빨리 보여주고 다시 시도할 길을 주는 쪽이 낫다.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 30_000,
      gcTime: 5 * 60_000,
      retry: 1,
      // 창을 다시 포커스할 때마다 부르지 않는다 — 웹에서 탭을 오갈 때마다
      // 요청이 나가면 이 티켓이 고치려는 증상이 그대로 돌아온다.
      refetchOnWindowFocus: false,
    },
  },
});
