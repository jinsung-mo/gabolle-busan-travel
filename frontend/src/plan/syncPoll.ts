// S15P21E201-1131 — 일정 화면이 이미 완성된 일정을 5초마다 다시 받는다.
//
// 🔴 먼저 티켓의 진단을 정정한다. 이 폴링은 「일정 생성이 끝났는지 기다리는 찌꺼기」가
//    아니다. **동행자의 변경을 받아오는 실시간 동기화**(S15P21E201-323)이고, 설계된
//    기능이다. 그래서 끄지 않는다 — 끄면 둘이 같이 고치는 여행에서 서로의 수정이
//    안 보인다.
//
// 대신 고치는 것은 **아무것도 안 바뀌는데도 같은 속도로 계속 묻는 것**이다. 혼자 보는
// 일정을 3분 열어 두면 요청이 36번 나가고, 그 36번이 전부 같은 답을 받는다.
//
// 규칙은 한 줄이다 — **바뀌면 빨라지고, 안 바뀌면 느려진다.**
//
//   5초 → 10 → 20 → 30 → 30 …        (계속 그대로일 때)
//   무엇이든 바뀌면 그 자리에서 다시 5초  (동행자가 손대기 시작한 순간)
//
// 3분(180초) 동안 아무 일도 없을 때 나가는 요청:
//
//   지금  t=5,10,15,…,180                     36회
//   이후  t=5,15,35,65,95,125,155,185          7회   (-81%)
//
// 🔴 최대 간격을 30초로 잡은 이유. 이 값은 「동행자가 고친 것이 내 화면에 늦게 보이는
//    최악의 시간」이다. 60초까지 늘리면 요청은 더 줄지만, 화면에 「실시간 동기화」라고
//    써 놓고 1분을 기다리게 하는 것은 말과 동작이 어긋나는 것이다. 그리고 실제로 둘이
//    같이 고치는 동안에는 변경이 계속 감지되므로 간격이 5초에 머문다 — 늘어난 간격은
//    **아무도 안 건드리는 동안에만** 쓰인다.

/** 기본 간격. 변화가 감지되면 언제나 이 값으로 되돌아간다. */
export const SYNC_POLL_BASE_MS = 5_000;

/** 최대 간격 = 동행자 변경이 보이기까지의 최악 지연. */
export const SYNC_POLL_MAX_MS = 30_000;

/**
 * 다음 주기까지 기다릴 시간.
 *
 * @param current 이번에 쓴 간격
 * @param changed 이번 응답이 화면을 바꿨는가(버전이 달랐는가)
 */
export function nextSyncPollDelay(current: number, changed: boolean): number {
	if (changed) return SYNC_POLL_BASE_MS;
	// 두 배씩, 최대치에서 멈춘다. 들어온 값이 이상해도 기본값 아래로는 안 내려간다.
	const doubled = Math.max(current, SYNC_POLL_BASE_MS) * 2;
	return Math.min(doubled, SYNC_POLL_MAX_MS);
}
