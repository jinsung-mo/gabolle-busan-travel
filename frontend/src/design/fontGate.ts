// 글꼴을 기다릴 것인가 — 루트 레이아웃이 화면을 비워 둘지 정하는 한 줄(S15P21E201-1510).
//
// 판정 자체는 간단한데 «틀리면 앱이 안 뜬다». 그래서 화면 밖으로 빼서 시험을 붙였다 —
// 루트 레이아웃을 통째로 그려서 확인하려면 라우터·공급자·알림까지 전부 세워야 하고,
// 그렇게 만든 시험은 이 규칙이 아니라 그 배선을 시험하게 된다.

/**
 * 글꼴이 실릴 때까지 화면을 비워 둘 것인가.
 *
 * 🔴 **실패는 기다림이 아니다.** 예전에는 `useFonts` 의 오류를 안 받아서 실패해도
 * 「아직 로딩 중」과 구분이 안 됐고, 글꼴이 한 번 실패하면 앱이 영영 빈 화면이었다.
 * 밖에서 보면 한 판 색에 접근성 요소 0개인데 프로세스는 살아 있어서, 멈춘 것인지
 * 고장 난 것인지조차 알 수 없다.
 *
 * 글꼴은 있으면 예쁜 것이지 앱이 뜨는 조건이 아니다. 실패하면 기기 기본 글꼴로 띄운다.
 */
export function shouldWaitForFonts(loaded: boolean, error: Error | null): boolean {
	return !loaded && !error;
}
