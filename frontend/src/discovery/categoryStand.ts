// 코스가 없어요」를 만난다. 🔴 고르기 전에 말해 준다 — 끝까지 가서 만나는 빈 화면이
// 가장 나쁘다. 개수는 서버(`GET /api/v1/places/categories`)에서 받으므로, 적재가 돌아
// 후보가 채워지면 이 코드를 안 고쳐도 저절로 풀린다.
//
// ── 🔴 왜 12 인가 (문턱을 60 에서 내린 이유) ─────────────────────────────────
//
// 처음에는 60 이었고 그것을 「추천 엔진이 요구하는 최소치」라고 적어 두었는데 **틀린
// 근거였다.** 근거로 삼은 백엔드 상수(`BaselineRecommendationEngine.MIN_AREA_CANDIDATES`)
// 는 「모자라면 실패」가 아니라 **「모자라면 출발지 기준으로 더 채운다」는 트리거**이고,
// 갈래마다가 아니라 «고른 갈래를 합친» 후보 수에 걸린다. 추천이 실제로 죽는 자리는
// 후보가 0건일 때다. 2026-09-16 운영에서 바다 4~6곳으로 돌렸을 때도 작업은 성공했다.
//
// 게다가 **바다는 60 을 영영 못 채운다.** 관광공사 부산 자료에서 자연이 전부 74곳이고
// 그중 해안이 32곳, 해수욕장은 9곳이다. 바다와 자연이 같은 74곳을 나눠 가지므로 어떻게
// 배분해도 둘 다 60 을 못 넘는다. 60 은 「적재가 돌면 풀리는 기준」이 아니라 바다에게는
// 영구 비활성이었고, 그 사이 비공개 테스트에서 테스터 12명이 갈래 넷을 아예 못 골랐다
// (2026-09-16 iOS 스윕).
//
// 그래서 엔진이 하루에 네 곳을 배정하는 것을 기준으로, 한 갈래만 골랐을 때 사흘치는
// 스스로 댈 수 있어야 한다고 보고 4 × 3 = 12 로 잡았다.
//
// 🔴 이 값도 «정확한 근거가 있는 값은 아니다» — 운영을 보고 조정할 값이다. 다만 60 과
// 달리 닿을 수 있는 수이고, 실제로 막아야 하는 것(후보가 한 줌뿐이라 일정이 안 서는
// 갈래)은 그대로 막는다.
//
// 🔴 2026-09-20 복원: 위 설명은 주석 정리(S15P21E201-1260)가 지웠던 것을 git 이력에서
// 되살린 것이다. 지워진 자리에 「범위 안 후보가 이보다 적으면…」이라는 조각만 남아
// 있었는데, 그것은 **이 상수가 아니라 위에 나오는 백엔드의 다른 상수**를 설명하던
// 인용문이었다. 남은 조각이 이 상수의 설명처럼 읽혀서, 2026-09-19 코드 분석이 이 파일의
// 12 를 「테스터 12명」으로 잘못 읽고 없는 버그를 하나 지어냈다. 낡은 주석보다
// **반쪽만 남은 주석이 더 나쁘다.**
export const MIN_CANDIDATES_PER_CATEGORY = 12;

export type CategoryStand = 'enough' | 'short';

/**
 * @param placeCount 서버가 낸 이 갈래의 장소 수. 서버는 place.category 에 실제로 있는 값만
 * 내므로, 응답에 아예 없는 갈래는 0곳이다 (undefined 를 0 으로 읽는 이유).
 */
export function categoryStand(placeCount: number | undefined): CategoryStand {
  return (placeCount ?? 0) >= MIN_CANDIDATES_PER_CATEGORY ? 'enough' : 'short';
}
