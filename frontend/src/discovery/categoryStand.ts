//
// 🔴 개수는 서버(GET /api/v1/places/categories)에서 받는다. 그래서 적재가 돌아 후보가
// 채워지면 이 코드를 고치지 않아도 저절로 풀린다. 어느 갈래가 부족한지를 여기 적어 두면
// 그 목록이 낡는 순간 거짓말이 된다.

// ── 🔴 2026-09-17 정정: 60 은 「엔진이 요구하는 최소치」가 아니었다 ─────────────
//
// 이 파일은 처음에 60 을 쓰고 그것을 엔진의 요구치라고 적어 두었다. 근거로 삼은 값은
// BaselineRecommendationEngine.MIN_AREA_CANDIDATES = 60 인데 그 상수의 뜻이 다르다.
//
//     /** 범위 안 후보가 이보다 적으면 출발지 기준으로 채운다 — S15P21E201-980.
//      *  ... 정확한 근거가 있는 값은 아니고 운영을 보고 조정할 값이다. */
//
// 「모자라면 실패」가 아니라 「모자라면 출발지 기준으로 더 채운다」는 트리거다. 게다가
// 갈래마다가 아니라 고른 갈래를 합친 후보 수에 걸리고, 작성자가 근거 없는 값이라고 직접
// 적어 두었다. 추천이 실제로 죽는 자리는 후보가 0건일 때(ENGINE_NO_CANDIDATES)다.
//
// 실측이 이를 뒷받침한다 — 2026-09-16 운영에서 바다 4~6곳으로 추천을 돌렸을 때 작업은
// SUCCEEDED 로 끝났다. 일정이 하루 한 곳으로 빈약했을 뿐 실패하지 않았다.
//
// ── 🔴 그리고 바다는 60 을 영영 못 채운다 ─────────────────────────────────────
//
// 관광공사 부산 자료를 총계로 세면(areaBasedList2 의 totalCount) 자연이 전부 74곳이고
// 그중 해안이 32곳, 진짜 해수욕장은 9곳이다. 바다와 자연은 같은 74곳을 나눠 가지므로
// 어떻게 배분해도 둘 다 60 을 넘길 수 없다. 부산에 해수욕장이 60곳 있지 않다.
//
// 즉 60 은 「적재가 돌면 저절로 풀리는 기준」이 아니라 바다에게는 영구 비활성이었다.
// 그 사이 비공개 테스트에서 테스터 12명이 갈래 넷을 아예 못 골랐다(2026-09-16 iOS 스윕).
//
// ── 그래서 무엇으로 바꿨나 ───────────────────────────────────────────────────
//
// 엔진이 하루에 네 곳을 배정한다(위 엔진 주석). 한 갈래만 골랐을 때 사흘치는 스스로 댈 수
// 있어야 고르게 둘 만하다고 보고 4 × 3 = 12 로 잡았다.
//
// 🔴 이 값도 정확한 근거가 있는 값은 아니다 — 엔진의 60 과 같은 성격이고 운영을 보고
// 조정할 값이다. 다만 60 과 달리 닿을 수 있는 수이고, 실제로 막아야 하는 것(후보가
// 0~한 줌뿐이라 일정이 안 서는 갈래)은 그대로 막는다.
export const MIN_CANDIDATES_PER_CATEGORY = 12;

export type CategoryStand = 'enough' | 'short';

/**
 * @param placeCount 서버가 낸 이 갈래의 장소 수. 서버는 place.category 에 실제로 있는 값만
 *   내므로, 응답에 아예 없는 갈래는 0곳이다 (undefined 를 0 으로 읽는 이유).
 */
export function categoryStand(placeCount: number | undefined): CategoryStand {
  return (placeCount ?? 0) >= MIN_CANDIDATES_PER_CATEGORY ? 'enough' : 'short';
}
