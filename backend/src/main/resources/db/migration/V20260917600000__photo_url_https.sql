--
--      안드로이드(API 28+)  usesCleartextTraffic 이 없으면 기본값이 차단
--      iOS                  앱 전송 보안(ATS)이 기본값으로 차단
--      웹                   https 페이지에서 http 이미지는 혼합 콘텐츠로 차단
--
--    앱 설정을 열어 평문을 허용하는 방법도 있지만, 그건 사진 하나 때문에 모든
--    통신에 평문 구멍을 내는 일이다.
--
-- 🔴 같은 주소가 https 로 그대로 열린다. 2026-09-17 에 직접 쟀다.
--
--      http://tong.visitkorea.or.kr/cms/resource/68/3026468_image2_1.JPG   → 200 image/jpg
--      https://tong.visitkorea.or.kr/cms/resource/68/3026468_image2_1.JPG  → 200 image/jpg
--
--    호스트도 경로도 같고 스킴만 다르다. 그래서 스킴만 바꾼다.
--
-- ── 🔴 아는 호스트만 바꾼다 ──────────────────────────────────────────────────
--
-- 조건을 tong.visitkorea.or.kr 로 좁힌다. 다른 호스트가 https 를 지원하는지는
-- 재 보지 않았고, 지원하지 않는 호스트를 바꾸면 지금 보이는 사진까지 깨진다.
-- 「안 보이는 것을 고치려다 보이는 것을 깨뜨리는」 쪽이 더 나쁘다.
--
-- 호스트가 늘면 재 보고 새 마이그레이션을 더한다. 이 문장을 LIKE 'http://%' 로
-- 넓히지 않는다 — 그건 재 보지 않은 것을 된다고 가정하는 일이다.
--
-- ── 🔴 번호를 맨 뒤에 둔 이유 ────────────────────────────────────────────────
--
-- 사진을 넣는 마이그레이션이 지금도 들어오는 중이다(S15P21E201-1182,
-- V20260917090000 이 257곳을 더 넣는다). 이 문장이 그보다 뒤에 와야 그 행까지
-- 함께 고쳐진다. 남의 MR 을 건드리지 않고 한 곳에서 끝내는 방법이다.
--
-- 🔴 정정 (2026-09-17) — 번호를 V20260917400000 에서 V20260917600000 으로 옮겼다.
--
--    위 문단은 「1182(V20260917090000)보다 뒤」만 보고 400000 을 골랐다. 그 사이
--    S15P21E201-1183(댓글)이 V20260917500000 을 달고 **먼저** back/dev 에 들어가
--    운영 DB 에 적용됐고(08:53), 그 뒤에 이 400000 이 머지됐다. Flyway 는 자기보다
--    큰 번호가 이미 적용된 뒤에 온 낮은 번호를 거부한다 —
--
--      Detected resolved migration not applied to database: 20260917400000.
--
--    그래서 배포 #363 이 기동조차 못 하고 되돌아갔다. 스키마가 깨진 게 아니라
--    번호 순서만 어긋난 것이라, 이 파일을 500000 뒤로 옮기는 것으로 끝난다.
--    내용은 한 글자도 안 바꿨다.
--
--    🔴 CI 의 backend:migration-order 검사는 이것을 못 잡는다. 그 잡은 **파이프라인이
--    도는 그 순간의** 대상 브랜치 최대 번호와 비교하는데, 통과한 뒤 머지 전에 다른
--    MR 이 더 큰 번호를 넣으면 그 결과가 낡는다. 마이그레이션을 더하는 MR 은
--    **머지 직전에 대상 브랜치를 한 번 당겨 파이프라인을 다시 돌려야** 한다.
--
-- 앞으로 들어오는 것은 적재기가 애초에 https 로 적는다(PhotoUrlScheme) —
-- 그쪽을 안 고치면 새 장소가 또 http 로 쌓이고 이 마이그레이션을 매번 다시 써야 한다.
--
-- ── 되돌리기 ─────────────────────────────────────────────────────────────────
--
-- 되돌릴 일이 없다. http 로 되돌리면 사진이 다시 안 보인다. 혹시 어떤 주소가
-- https 에서 404 를 내면 그건 스킴 문제가 아니라 그 사진이 원천에서 사라진 것이고,
-- 되돌려도 마찬가지로 안 나온다.

UPDATE place
   SET photo_url = 'https://' || substring(photo_url FROM 8)
 WHERE photo_url LIKE 'http://tong.visitkorea.or.kr/%';
