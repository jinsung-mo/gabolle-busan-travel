-- 썸네일이 없는 동영상을 허용한다 — S15P21E201-1279.
--
-- 🔴 V20260918170000 이 이 칸을 NOT NULL 로 만들었다. 그 판단이 틀렸다.
--
-- 「줄이기·썸네일·길이 재기를 앱이 한다」(2026-09-18 결정)를 「앱이 언제나 성공한다」로 읽고
-- 필수로 박았다. 실제로는 앱이 썸네일을 만들다 실패할 수 있고, 그때 **「동영상은 올라갔는데
-- 썸네일만 없다」가 정상 상태**여야 한다. 필수로 두면 그 동영상을 아예 저장할 수 없다.
--
-- 웹에서 올리는 길을 열게 되면 더 분명해진다 — 압축도 썸네일 만들기도 네이티브 기능이라
-- 브라우저에서는 둘 다 없이 올라온다. 다만 그 결정을 기다릴 필요가 없다. 웹을 안 열어도
-- 앱의 실패만으로 이 상태가 생긴다.
--
-- 🔴 앞의 마이그레이션을 고치지 않고 새 파일로 하는 이유
--
-- V20260918170000 은 이미 back/dev 에 머지됐다. Flyway 는 적용한 파일의 지문(체크섬)을
-- flyway_schema_history 에 저장해 두고 기동할 때마다 대조하므로, 그 파일을 한 글자라도
-- 고치면 **서버가 아예 안 뜬다.** 이 팀이 2026-09-15 에 실제로 겪은 종류의 고장이다.
--
-- 🔴 기존 행과 부딪히지 않는다 — 운영에 이 표가 아직 없다
--
-- 2026-09-18 확인: 운영 DB 에서 to_regclass('gabolle.story_video') 가 빈 값이다. 즉 앞의
-- 마이그레이션이 아직 배포되지 않았고 행이 한 건도 없다. 제약을 **푸는** 방향이라 행이
-- 있었더라도 안전하지만, 그 사실을 재 보고 적어 둔다.

ALTER TABLE story_video ALTER COLUMN thumbnail_upload_id DROP NOT NULL;

-- 🔴 uq_story_video_thumbnail(UNIQUE)은 그대로 둔다 — 다시 재지 않아도 된다.
--
-- 「썸네일 없는 동영상이 둘이면 UNIQUE 에 부딪히지 않나」가 자연스러운 의문인데 안 부딪힌다.
-- Postgres 의 UNIQUE 는 NULL 을 서로 다른 값으로 취급해서 **NULL 은 몇 개든 들어간다.**
-- 값이 있는 썸네일끼리만 유일성이 걸리고, 그게 원래 이 제약이 막으려던 것이다 —
-- 한 파일이 두 기록에 붙으면 한쪽을 지울 때 다른 쪽이 깨진다.

COMMENT ON COLUMN story_video.thumbnail_upload_id IS
    '썸네일 파일의 업로드 id. 앱이 썸네일을 못 만들었으면 NULL — 「동영상은 있고 썸네일만 없다」는 정상 상태다. 화면이 그때 무엇을 그릴지는 화면이 정한다.';
