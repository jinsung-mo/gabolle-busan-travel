-- S15P21E201-1544 — 「묵는 동네」를 받는 칸. 2026-09-23 장효준 결정(C).
--
-- 왜. 앱의 숙소 칸은 검색어가 없을 때 추천 동네 넷을 먼저 보여 준다 — 가장 많이 눌릴
-- 자리다. 그것을 S15P21E201-1522 의 숙소 스냅샷으로 보내면 서버에 장소 행 「해운대」가
-- 생기는데, 재 보니 그 넷이 TravelArea 와 좌표까지 같았다.
--
--   앱  lodging-haeundae  35.1587, 129.1604
--   서버 HAEUNDAE("해운대", 35.1587, 129.1604, 2500)
--
-- 어휘가 이미 두 벌인데 장소까지 만들면 셋이 되고 서로 조인이 안 된다. TravelArea 주석이
-- 그 상황을 이미 경고하고 있다 — "같은 「해운대」가 여행마다 다른 곳을 뜻하게 된다".
-- 그래서 장소로 만들지 않고 코드로 받는다. 지금은 앱이 아예 안 싣고 있어(!1525) 신호가
-- 버려지는 상태이고, 이 칸이 그것을 받는다.
--
-- 🔴 어휘를 CHECK 로 박지 않는다. trip_travel_area.area_code 선례 그대로다 —
--    좌표는 표가 아니라 코드(TravelArea)가 들고 있고, 표에 적으면 지역 중심을 옮길 때
--    이미 만든 여행만 옛 좌표로 남는다. 값 목록을 SQL 에 박으면 지역을 하나 더하는 일이
--    이관 하나를 요구하게 되는 것도 같은 이유로 피한다.
--
-- 🔴 accommodation_place_id 와 겹치지 않는다. 앞엣것은 「정확한 숙소 한 곳」이고 이 칸은
--    「묵는 동네」다 — 표현하는 대상이 다르고 둘 다 있을 수 있다. 둘 다 비면 아직 안 정한
--    것이다. 엔진이 무엇을 먼저 볼지는 숙박이 낀 날의 동선 결정이 붙을 때 정한다.
ALTER TABLE trip
    ADD COLUMN accommodation_area VARCHAR(30);

COMMENT ON COLUMN trip.accommodation_area IS
    '묵는 동네. TravelArea 코드다(HAEUNDAE·SEOMYEON 등) — 앱 어휘(lodging-haeundae)가 아니라 서버 어휘로 저장한다. accommodation_place_id(정확한 숙소 한 곳)와 다른 사실이고 둘 다 있을 수 있다 (S15P21E201-1544).';
