-- 이름 열쇠 — 위 씨앗의 name_key 와 같은 규칙(생성 스크립트의 key()).
CREATE TEMPORARY TABLE place_local_name_match AS
SELECT DISTINCT ON (p.place_id, s.lang) p.place_id, s.lang, s.name_local
FROM place p
CROSS JOIN LATERAL (
    SELECT regexp_replace(regexp_replace(lower(p.name_ko), '[(（][^)）]*[)）]', '', 'g'), '[^0-9a-z가-힣]', '', 'g') AS full_key
) k
JOIN place_local_name_seed s
  ON abs(p.lat - s.lat) < 0.0045
 AND abs(p.lng - s.lng) < 0.0055
 AND (k.full_key = s.name_key
      -- 「부산 자갈치시장」 = 「자갈치시장」. 「부산」을 빼고 두 글자 미만이면(부산역 → 역) 이 길로는 잇지 않는다.
      OR (char_length(s.short_key) >= 2 AND replace(k.full_key, '부산', '') = s.short_key))
-- 한 장소에 여럿이 맞으면: 원래 이름이 그대로 같은 쪽 → 가까운 쪽.
ORDER BY p.place_id, s.lang, (k.full_key = s.name_key) DESC, abs(p.lat - s.lat) + abs(p.lng - s.lng);

UPDATE place p SET name_ja = m.name_local
FROM place_local_name_match m
WHERE m.place_id = p.place_id AND m.lang = 'ja' AND p.name_ja IS NULL;

UPDATE place p SET name_zh_hans = m.name_local
FROM place_local_name_match m
WHERE m.place_id = p.place_id AND m.lang = 'zh-Hans' AND p.name_zh_hans IS NULL;

UPDATE place p SET name_zh_hant = m.name_local
FROM place_local_name_match m
WHERE m.place_id = p.place_id AND m.lang = 'zh-Hant' AND p.name_zh_hant IS NULL;

DROP TABLE place_local_name_match;
DROP TABLE place_local_name_seed;
