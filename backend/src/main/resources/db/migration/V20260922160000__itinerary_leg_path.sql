-- S15P21E201-1251 — 구간에 「어느 길로 가는지」(선형)를 담는다.
--
-- 🔴 왜 필요한가. itinerary_leg 에 들어 있는 것은 출발 장소·도착 장소·거리·시간뿐이라
--    「어느 길로 가는지」가 없다. 그래서 두 가지가 막혀 있다.
--
--    ① 지도에 실제 길이 아니라 두 점을 잇는 직선이 그려진다. 프론트(S15P21E201-1234 —
--       「실제 길은 실선, 추정은 점선」)가 이 칸을 기다리고 있다.
--    ② 그늘·경사를 길에 못 얹는다. 앱의 「그늘길 우선」·「경사 피하기」·「계단 피하기」
--       스위치는 셋 다 「길 환경」 칸에 있는데, 선형이 없어 지금은 **추천되는 장소**만
--       바꾸고 **걷는 길**은 안 바꾼다. 켜도 길이 그대로다.
--
-- 🔴 그러면서 정작 선형은 이미 받아 놓고 버리고 있었다.
--    KakaoMobilityRouteAdapter 가 업체 응답에서 좌표를 파싱해 RouteLeg.path 에 담는데,
--    RouteTravelTimeAdapter 가 TravelTime 으로 옮길 때 거리·시간·요금만 가져가고 선형을
--    떨어뜨린다. 포트가 좁아서 생긴 손실이지 자료가 없어서가 아니다.
--    (V20260916180000__itinerary_leg_fare.sql 이 요금에서 똑같은 것을 고쳤다.)
--
-- 🔴 왜 JSONB 인가. 좌표 배열이라 행으로 펴면 구간 하나가 수십 행이 되고, 읽을 때 언제나
--    다시 모아야 한다. 이 값은 통째로 쓰이거나 아예 안 쓰이지 가운데가 없다 —
--    부분 질의를 할 일이 없으므로 한 칸에 둔다. PostGIS 를 들이지 않는 이유도 같다:
--    지금 필요한 것은 공간 연산이 아니라 「그려 줄 좌표 목록」이다.
--
-- 🔴 좌표 순서는 [경도, 위도] 다. GeoJSON·지도 라이브러리와 같은 순서이고
--    RouteLeg.path 의 주석이 이미 그렇게 못 박아 뒀다. 여기서 순서를 뒤집으면 그 두 곳과
--    어긋나면서, 부산 좌표는 위도 35·경도 129 라 뒤집혀도 숫자가 그럴듯해 보여서
--    화면에 그려 보기 전까지 아무도 못 알아챈다.
--
-- 기존 행은 NULL 로 남는다. 이 기능 이전에 만들어진 구간이 어느 길로 갔는지는 알 수 없고,
-- 모르는 것을 직선으로 적으면 「실제로 잰 길」과 구분이 사라진다 — 화면이 실선으로 그린다.
-- (V20260908220000__itinerary_leg_data_status.sql 이 같은 이유로 같은 선택을 했다.)
ALTER TABLE itinerary_leg
    ADD COLUMN path JSONB;

-- 선형이 있으면 점이 둘은 있어야 한다. 점 하나짜리 선은 길이 아니고, 빈 배열은 「없다」를
-- 「잰 결과가 비었다」로 바꿔 적는 것이라 둘 다 막는다 — 없으면 NULL 이다.
ALTER TABLE itinerary_leg
    ADD CONSTRAINT ck_itinerary_leg_path
        CHECK (path IS NULL OR (jsonb_typeof(path) = 'array' AND jsonb_array_length(path) >= 2));

COMMENT ON COLUMN itinerary_leg.path IS
    '이 구간이 지나는 길의 좌표 목록. [[경도,위도], …] 순서(GeoJSON 과 같다). NULL=어느 길로 갔는지 모른다';
