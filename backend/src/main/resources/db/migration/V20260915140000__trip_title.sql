-- 여행에 이름 칸을 만든다 — S15P21E201-1023.
--
-- 🔴 왜 필요한가: 여행 카드의 제목 자리가 날짜뿐이라, **같은 날짜로 두 번 계획하면 두 카드가
--    글자 하나 다르지 않다.** 그리고 「다시 짜 보기」는 이 서비스의 기본 동작이라 드문 일이
--    아니다. 비공개 테스트에 테스터 12명이 2주 동안 들어가는데, 자기가 뭘 만들었는지 못 찾으면
--    그 피드백은 기능이 아니라 길 잃음에 대한 것이 된다.
--
-- 🔴 NULL 을 허용한다. 채우지 않는다.
--    이미 있는 여행에 지어낸 이름을 박으면 «사용자가 붙인 이름» 과 «서버가 만든 이름» 이
--    같은 칸에서 구분이 안 된다. NULL 은 「아직 이름이 없다」는 뜻이고, 그때 화면은 지금처럼
--    날짜를 제목으로 쓴다 — 그래서 이 마이그레이션은 기존 여행을 하나도 안 깨뜨린다.
--
-- 길이 60 은 카드 한 줄에 들어가는 한계에서 왔다. 도메인(Trip.rename)도 같은 값을 본다 —
-- DB 제약이 먼저 터지면 어느 필드가 문제인지 응답에 안 남기 때문이다.

ALTER TABLE trip ADD COLUMN title varchar(60);

COMMENT ON COLUMN trip.title IS
    '사용자가 붙인 여행 이름. NULL 이면 아직 이름이 없다 — 화면이 날짜를 제목으로 쓴다 (S15P21E201-1023)';
