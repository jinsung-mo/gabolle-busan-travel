-- S15P21E201-1109 — 구간의 이동 요금을 남긴다.
--
-- 🔴 왜 필요한가. 일정 화면의 「예상 비용」이 출처 없는 숫자였다. 운영 실측으로
--    itinerary_item.estimated_cost_krw 는 411개 전부 NULL 이고, 저장소 어디에도 그 칸에
--    숫자를 넣는 코드가 없다. 그런데 화면에는 금액이 찍힌다 — 아무 오류도 안 나면서
--    사용자에게 없는 사실을 말하는 상태다.
--
--    그러면서 정작 진짜 요금은 받아 놓고 버리고 있었다. KakaoMobilityRouteAdapter 가
--    카카오모빌리티 응답에서 택시 요금과 통행료를 파싱해 RouteLeg 에 담는데, 거기서 끊겨
--    아무도 안 읽는다. 이 칸이 그 값을 받을 자리다.
--
-- 🔴 왜 itinerary_item 이 아니라 itinerary_leg 인가.
--    요금은 "A 에서 B 로 가는 데 드는 돈" 이라 구간의 성질이고, 입장료는 "그 장소에 들어가는
--    데 드는 돈" 이라 장소의 성질이다. 한 칸에 합치면 입장료 자료가 없는 지금
--    **「교통비만 낸 합계」가 「총비용」으로 읽힌다** — 고치려는 거짓말과 같은 종류가 된다.
--
-- 🔴 NULL 과 0 은 다르다. NULL 은 "얼마인지 모른다" 이고 0 은 "공짜다" 다.
--    지금 값이 들어가는 것은 자동차 계열(택시·자가용·렌터카)뿐이다 — 카카오모빌리티가
--    자동차 경로만 주기 때문이다(그 어댑터의 supports 가 CAR 에만 참을 준다).
--    도보에는 요금이라는 것이 없고, 대중교통은 업체가 주지 않는다. 그때 0 으로 메우면
--    화면이 전부 「무료」로 그린다. 그래서 비워 둔다.
--
--    대중교통 운임은 별건이다. 노선망이 들어오면 탄 노선·구간·환승 횟수로 계산할 수 있다
--    (S15P21E201-1104 의 탐색 결과가 그 셋을 이미 안다).
--
-- 기존 행은 NULL 로 남는다. 이 기능 이전에 만들어진 구간이라 요금이 얼마였는지 알 수 없고,
-- 모르는 것을 0 으로 적는 것은 주장이므로 아예 비워 둔다
-- (V20260908220000__itinerary_leg_data_status.sql 이 같은 이유로 같은 선택을 했다).
ALTER TABLE itinerary_leg
    ADD COLUMN fare_krw INTEGER;

ALTER TABLE itinerary_leg
    ADD CONSTRAINT ck_itinerary_leg_fare_krw
        CHECK (fare_krw IS NULL OR fare_krw >= 0);

COMMENT ON COLUMN itinerary_leg.fare_krw IS
    '이 구간의 이동 요금(원). NULL=모른다(도보·대중교통 등 출처 없음), 0=공짜. 둘은 다르다';
