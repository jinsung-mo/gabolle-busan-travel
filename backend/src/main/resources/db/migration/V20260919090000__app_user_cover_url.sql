-- 계정에 커버 사진 주소 칸을 만든다 (S15P21E201-1297)
-- ══════════════════════════════════════════════════════════════════════════════
--
-- 마이페이지 맨 위에 전폭으로 깔리는 사진이다. 지금은 서버에 칸이 아예 없어서
-- (2026-09-19 실측 — backend 전체에서 cover_url 0건) 화면을 만들어도 **모든 사람이
-- 같은 기본 사진만 보고 바꿀 수 없다.**
--
-- 사진 파일 자체는 이미 있는 업로드 자리(POST /api/v1/uploads/story-image)에 올라가고
-- 표에는 그 주소만 남는다. avatar_url(S15P21E201-844)이 같은 방식이고, 이 칼럼은
-- 그 옆에 나란히 선다.


-- ── 길이를 500 으로 맞춘 이유 ────────────────────────────────────────────────
--
-- avatar_url 과 같다. uploaded_image.image_url 이 VARCHAR(500) 이고 여기 들어올 값이
-- 바로 그 칼럼에서 나온 주소다. 담는 쪽이 내는 쪽보다 좁으면 **올린 사진 중 일부만
-- 커버로 못 쓰는** 상태가 된다.
ALTER TABLE app_user
    ADD COLUMN cover_url VARCHAR(500);


-- ── NULL 이 기본이고, 그것이 "안 골랐다" 다 ──────────────────────────────────
--
-- 빈 문자열도, 기본 사진 주소도 넣지 않는다. 기본 사진 주소를 넣으면 "사용자가 고른
-- 사진" 과 "아직 안 고른 사람" 을 표에서 구분할 수 없게 되고, 나중에 기본 사진을
-- 바꾸려면 그 값을 넣은 행을 전부 찾아 고쳐야 한다 — 어느 것이 사용자의 선택이었는지
-- 알 방법이 없는 채로.
--
-- **기본 사진을 고르는 것은 화면의 몫**이다. 표는 "안 골랐다" 만 말한다.
ALTER TABLE app_user
    ADD CONSTRAINT ck_app_user_cover_url_not_blank
        CHECK (cover_url IS NULL OR length(btrim(cover_url)) > 0);

COMMENT ON COLUMN app_user.cover_url IS
    '커버 사진 주소. 본인이 올린 사진의 주소만 들어온다. NULL 은 안 골랐다는 뜻 (S15P21E201-1297)';
