--
-- S15P21E201-475 가 연 기록 경로는 여행 안에서만 부를 수 있다. 그런데 로컬 탐색 화면
-- (S15P21E201-127)은 여행에 속하지 않는 전역 탭이라 실을 trip_id 가 없어서 **한 번도
-- 기록을 못 남기고 있었다.** 475 의 목적이 이용 집계인데 여행 밖 열람이 통째로 빠지면
-- 그 집계로 우선순위를 정할 수 없다.
--
-- 🔴 표를 나누지 않는다. 나누면 집계가 두 곳을 더해야 하고, 더하는 것을 잊은 화면이
--    한 곳이라도 생기면 그때부터 숫자가 조용히 반쪽이 된다. 같은 표에 넣고 trip_id 가
--    비어 있는 것으로 구분한다.


-- ── trip_id 를 비울 수 있게 한다 ────────────────────────────────────────────
--
-- 🔴 이 칼럼이 NOT NULL 이었던 것은 「어느 여행에서 열었나」가 475 의 유일한 기록
--    경로였기 때문이지, 그 값이 기록의 본질이라서가 아니다. 본질은 facet_key 와
--    viewed_at 이고 그 둘은 그대로 NOT NULL 이다.
--
-- 🔴 NULL 이 「전역 탐색에서 열었다」 다. 0 이나 빈 UUID 같은 표식을 쓰지 않는다 —
--    그런 값은 외래 키를 못 걸고, 무엇보다 **실제 여행 번호와 같은 칸에 섞여** 다음
--    사람이 그것을 여행으로 착각해 조인한다.
ALTER TABLE place_facet_view
    ALTER COLUMN trip_id DROP NOT NULL;

COMMENT ON COLUMN place_facet_view.trip_id IS
    '어느 여행에서 열었나. NULL 은 여행에 안 묶인 전역 탐색에서 열었다는 뜻 (S15P21E201-894)';
