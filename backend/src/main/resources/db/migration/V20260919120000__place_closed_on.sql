-- 문 닫은 가게를 추천하지 않기 위한 칸 — S15P21E201-1341.
--
-- 🔴 왜 필요한가
--
-- 장소는 소상공인 상가정보와 한국관광공사에서 들어온다. 둘 다 **그 시점에 영업 중이던**
-- 가게 목록이고, 그 뒤에 문을 닫아도 우리 표는 그대로다. 적재기에 그렇게 적혀 있다 —
-- 「이미 있는 장소는 건너뛴다 — 고치지 않는다. "다음 분기 파일로 갱신한다"(폐업·이전·
-- 상호 변경을 어떻게 반영하나)는 별개의 결정이라 여기서 미리 정하지 않는다」.
--
-- 그 별개의 결정이 이것이다. 폐업 여부를 담을 자리를 만든다.
--
-- 🔴 「모른다」와 「영업 중」은 다르다
--
-- NULL 은 **폐업이 아니다. 「모른다」다.** 인허가 자료와 안 이어진 장소가 많다 —
-- 해수욕장·전망대는 애초에 음식·주류 인허가가 없다. 그것을 폐업으로 떨어뜨리면
-- 멀쩡한 곳이 통째로 사라진다. 그래서 추천에서 빼는 것은 **값이 실제로 있는 줄뿐**이다.
--
-- 🔴 참거짓 칸을 따로 두지 않는다
--
-- `closed_on IS NOT NULL` 이 곧 「닫았다」다. 칸을 둘로 두면 한쪽만 고쳐지는 날이 오고,
-- 그때 어느 쪽이 진짜인지 아무도 모른다.
ALTER TABLE place ADD COLUMN IF NOT EXISTS closed_on DATE;

COMMENT ON COLUMN place.closed_on IS
	'폐업일자. NULL 은 「영업 중」이 아니라 「모른다」다 — 인허가 자료와 안 이어진 장소가 많다 (S15P21E201-1341)';

-- 추천 후보를 고를 때마다 이 칸을 본다. 닫은 곳은 소수라 부분 색인이 알맞다 —
-- 전체 색인을 만들면 NULL(대다수)까지 담아 쓸모에 비해 커진다.
CREATE INDEX IF NOT EXISTS ix_place_closed_on ON place (closed_on) WHERE closed_on IS NOT NULL;
