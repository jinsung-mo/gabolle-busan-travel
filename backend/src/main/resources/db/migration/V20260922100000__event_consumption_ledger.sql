-- S15P21E201-561 — 브로커에서 받은 이벤트를 "한 번만" 반영했다는 것을 표로 증명한다.
--
-- 완료 기준이 요구하는 것: "consumer 재시작·중복 전달에도 정제 데이터가 한 번만 반영된다".
--
-- ── 왜 코드가 아니라 기본키로 막나 ────────────────────────────────────────────
--
-- 소비자 쪽에서 "이미 처리했나" 를 먼저 조회하고 아니면 처리하는 식으로 짜면, 같은
-- 이벤트가 두 소비자에게 동시에 가는 순간 둘 다 "아직 안 했다" 를 보고 둘 다 처리한다
-- (검사와 쓰기 사이에 틈이 있다). 그 틈은 테스트로는 거의 안 잡히고 운영에서만 난다.
--
-- event_id 를 기본키로 두면 그 틈이 **없어진다.** 두 번째 INSERT 는 데이터베이스가 거부한다.
-- 소비자는 그 거부를 "이미 반영됨" 으로 읽고 조용히 넘어가면 된다.
--
-- ── 왜 payload 를 복사하지 않나 ──────────────────────────────────────────────
--
-- 본문은 event_outbox 에 이미 있다. 여기 한 벌 더 두면 둘이 어긋날 수 있고, 어긋나도
-- 아무 오류가 안 난다. 이 표는 "무엇이 들어왔나" 가 아니라 **"무엇을 이미 반영했나"** 만
-- 안다. 본문이 필요하면 event_id 로 원본을 본다.
--
-- ── 이 표는 「정제 데이터」가 아니다 ─────────────────────────────────────────
--
-- 🔴 지금 소비자가 하는 일은 "받았다고 적는 것" 뿐이다. 취향 벡터에 귀속시키는 진짜 정제는
--    S15P21E201-1061(행동을 취향 무게로 바꾸는 규칙)이 사람 손으로 정해져야 시작할 수 있다.
--    그 규칙 없이 숫자를 만들면 좋아요 한 번의 무게를 지어내게 된다. 그래서 여기서 멈춘다 —
--    경로가 뚫렸다는 것과 무게를 정했다는 것은 다른 일이다.

CREATE TABLE event_consumption (
    -- 🔴 브로커가 보낸 헤더 event_id 그대로다. 릴레이는 "정확히 한 번" 이 아니라
    --    "적어도 한 번" 을 보장하므로 같은 값이 두 번 올 수 있고, 그때 이 기본키가 막는다.
    event_id        UUID         PRIMARY KEY,

    event_type      VARCHAR(64)  NOT NULL,

    -- 순서를 지켜야 하는 단위. event_outbox.partition_key 와 같은 값이고 카프카 메시지
    -- 키이기도 하다 — 나중에 "이 여행의 이벤트가 순서대로 왔나" 를 이 칸으로 따진다.
    partition_key   VARCHAR(128) NOT NULL,

    -- 어느 소비자 묶음이 반영했나. 묶음이 둘 이상이 되면 같은 이벤트를 각자 한 번씩
    -- 반영해야 하므로, 그때는 기본키를 (event_id, consumer_group) 으로 넓힌다.
    -- 지금은 묶음이 하나라 event_id 만으로 충분하다.
    consumer_group  VARCHAR(128) NOT NULL,

    -- 되짚어 볼 때 필요한 좌표. 브로커에서 같은 자리를 다시 읽으려면 이 둘이 있어야 한다.
    kafka_partition INTEGER      NOT NULL,
    kafka_offset    BIGINT       NOT NULL,

    consumed_at     TIMESTAMPTZ  NOT NULL
);

COMMENT ON TABLE event_consumption IS
    'S15P21E201-561 — 브로커에서 받아 이미 반영한 이벤트의 장부. event_id 가 기본키라 중복 전달이 데이터베이스 수준에서 한 번으로 줄어든다. 본문은 여기 없다 — event_outbox 가 정본이다.';

COMMENT ON COLUMN event_consumption.consumer_group IS
    '소비자 묶음 이름. 묶음이 둘 이상이 되면 기본키를 (event_id, consumer_group) 으로 넓혀야 한다 — 지금 구조로는 두 번째 묶음이 같은 이벤트를 반영하지 못하고 조용히 건너뛴다.';

-- 시간대별 조회(완료 기준의 "lag 과 실패 유형을 시간대별로 조회") 용.
CREATE INDEX ix_event_consumption_consumed_at ON event_consumption (consumed_at);
