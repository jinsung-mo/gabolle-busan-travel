-- 프로필 사진 주소를 사용자 레코드에 둔다 (S15P21E201-844)
-- ══════════════════════════════════════════════════════════════════════════════
--
-- 지금 프로필 사진은 앱이 기기 안에만 저장한다. 그래서 기기를 바꾸면 사라지고,
-- 무엇보다 **다른 사람 화면에는 아예 안 보인다** — 팔로우 목록도 여행 동행자 카드도
-- 서버가 준 값으로 그리기 때문이다. 서버에 칸이 없으니 줄 값이 없었다.
--
-- 사진 파일 자체는 이미 있는 업로드 자리(POST /api/v1/uploads/story-image)에 올라가고
-- 표에는 그 주소만 남는다. uploaded_image 가 같은 방식이다.


-- ── 길이를 500 으로 맞춘 이유 ────────────────────────────────────────────────
--
-- uploaded_image.image_url 이 VARCHAR(500) 이다. 여기 들어올 값이 바로 그 칼럼에서
-- 나온 주소이므로 더 짧게 잡으면 **올린 사진 중 일부만 프로필로 못 쓰는** 상태가 된다.
-- 담는 쪽이 내는 쪽보다 좁으면 안 된다.
ALTER TABLE app_user
    ADD COLUMN avatar_url VARCHAR(500);


-- ── NULL 이 기본이고, 그것이 "안 골랐다" 다 ──────────────────────────────────
--
-- 빈 문자열을 기본값으로 두지 않는다. 빈 문자열은 "주소가 있는데 비어 있다" 로 읽혀서
-- 화면이 깨진 이미지를 그리게 된다. 사진을 안 고른 사람과 고른 사람을 NULL 하나로
-- 가른다.
--
-- 🔴 빈 문자열이 실수로 들어오는 것도 막는다. 서버가 이미 거부하지만, 이 칸에 값을
--    넣는 경로가 앞으로 늘어날 수 있고 그때 같은 실수를 여기서 한 번 더 잡는다.
ALTER TABLE app_user
    ADD CONSTRAINT ck_app_user_avatar_url_not_blank
        CHECK (avatar_url IS NULL OR length(btrim(avatar_url)) > 0);

COMMENT ON COLUMN app_user.avatar_url IS
    '프로필 사진 주소. 업로드 자리가 돌려준 주소만 들어온다. NULL 은 안 골랐다는 뜻 (S15P21E201-844)';
