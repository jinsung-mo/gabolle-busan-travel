package com.gabolle.backend.place.domain;

/**
 * 이 장소 행을 추천 후보로 써도 되는가 — S15P21E201-1426.
 *
 * <p><b>출처({@code source_type})와 다른 질문이다.</b> 출처는 「어느 수집분에서 왔나」이고
 * 이것은 「사람이 검증했나」다. 둘을 한 칸으로 쓰면 안 되는 이유가 실제로 있다 —
 * {@code source_type = 'KAKAO_LOCAL'} 인 행이 이미 넷 있는데(해운대해수욕장·광안리해수욕장·
 * 감천문화마을·범어사, {@code V20260916210000}) 앱의 대표 카드가 쓰는 핵심 명소라 추천에
 * 반드시 들어가야 한다. 출처로 걸러내면 이 넷이 같이 사라진다.
 */
public enum CurationStatus {

	/** 적재기나 큐레이션이 넣었다. 추천 후보로 쓴다. */
	CURATED,

	/**
	 * 사용자가 기록에 붙이려고 고른 장소라 서버가 만들었다. 품질이 검증되지 않아 추천
	 * 후보에서 뺀다 — 이름·좌표가 남의 검색 결과 그대로이고 아무도 안 봤다.
	 */
	USER_SUBMITTED,

	/**
	 * 같은 장소의 다른 줄로 합쳐졌다 — S15P21E201-1619. 지우지 않고 남겨 둔 줄이라 번호로는 열리지만(옛 일정·기록),
	 * 찾아 주는 조회에서는 빠진다. 어느 줄로 합쳐졌는지는 {@code Place.getMergedInto()} 에 있다.
	 */
	MERGED
}
