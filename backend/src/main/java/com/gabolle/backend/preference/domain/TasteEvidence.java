package com.gabolle.backend.preference.domain;

/**
 * 취향 벡터의 숫자 하나가 <b>어디서 나왔는가</b>.
 *
 * <p>🔴 이것을 안 남기면 "설문에서 직접 고른 것" 과 "행동을 보고 우리가 추측한 것" 이
 * 같은 값으로 보인다. 둘은 다르게 다뤄야 한다 — 사람이 직접 고른 것을 우리 추측으로
 * 덮어쓰면 안 되고, 화면에서 "왜 이걸 추천했나" 를 설명할 때도 말이 달라진다.
 * ("조용한 곳을 고르셨어요" vs "조용한 곳에 오래 머무르셨어요")
 */
public enum TasteEvidence {

	/** 설문에서 사람이 직접 골랐다. */
	SURVEY,

	/** 앱에서의 행동만으로 추측했다. 사람이 그 차원을 답한 적이 없다. */
	INTERACTION,

	/** 설문 답을 행동으로 보정했다. */
	BLENDED
}
