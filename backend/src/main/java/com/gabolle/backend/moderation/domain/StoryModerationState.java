package com.gabolle.backend.moderation.domain;

/**
 * 기록의 신고 검토 상태 — S15P21E201-254 · -267.
 *
 * <h2>🔴 {@code deleted_at} 과 다른 칸인 이유</h2>
 * 신고를 받으면 기록이 즉시 안 보여야 하고, 운영자가 기각하면 <b>다시 보여야 한다.</b>
 * 작성자가 지운 것({@code deleted_at})은 되살리지 않는다. 두 사실을 한 칸에 담으면 "지운 것"
 * 과 "잠깐 감춘 것" 을 구분할 수 없고, 신고당한 사람에게도 자기 기록이 삭제된 것으로 보인다.
 *
 * <p>대가는 <b>조회 경로를 전부 고쳐야 하는 것</b>이다. 피드·상세·프로필 피드가 각각 이 값을
 * 봐야 하고, 하나라도 빠뜨리면 신고된 기록이 그 화면에만 계속 보인다. 그래서 빠뜨림을 재는
 * 테스트가 이 기능의 절반이다.
 */
public enum StoryModerationState {

	/** 정상. 피드와 상세에 보인다. */
	VISIBLE,

	/**
	 * 신고를 받아 검토 대기 중. 🔴 <b>즉시</b> 피드와 상세에서 빠진다 — 운영자가 볼 때까지
	 * 그대로 노출하면 신고 창구가 있는 의미가 없다(개인정보가 노출된 사진이 운영자 출근까지
	 * 계속 보인다면 신고를 받은 것이 아니다).
	 */
	UNDER_REVIEW,

	/** 운영자가 삭제로 처리했다. 되돌리지 않는다. */
	REMOVED;

	/** 이 상태의 기록이 남에게 보이는가. */
	public boolean visibleToOthers() {
		return this == VISIBLE;
	}
}
