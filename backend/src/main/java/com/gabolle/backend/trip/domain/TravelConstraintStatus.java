package com.gabolle.backend.trip.domain;

/**
 * 여행 조건 모달에 사람이 준 답 — S15P21E201-1231.
 *
 * <h2>🔴 여기 없는 넷째 상태 — 「한 번도 안 물어봤다」</h2>
 *
 * 그것은 이 enum 의 값이 아니라 <b>행이 없는 것</b>이다. 응답에서는 {@code status: null} 로
 * 나간다. 값으로 두지 않는 이유는, 그것이 사람이 준 답이 아니라 <b>아직 아무 일도 안 일어난
 * 상태</b>라서다 — 여기에 넣으면 가입한 모든 사람에게 빈 행이 하나씩 생기고, 그 행은
 * 아무것도 안 알려 준다.
 *
 * <h2>🔴 {@link #LATER} 와 {@link #NEVER} 를 합치지 않는다</h2>
 *
 * 둘 다 「지금은 안 한다」로 보이지만 <b>다음에 할 일이 정반대</b>다. 합치면 사용자가
 * <b>끄고 싶은 모달을 매번 보거나, 켜고 싶은 모달을 영영 못 본다.</b>
 */
public enum TravelConstraintStatus {

	/**
	 * 「저장하고 시작」 — 값이 있다. 더 안 묻는다.
	 *
	 * <p>🔴 이 상태일 때만 {@code value} 가 채워진다. DB 의
	 * {@code ck_user_travel_constraint_value_matches_status} 가 그 짝을 강제한다.
	 */
	SAVED,

	/**
	 * 「나중에」 — 값이 없다.
	 *
	 * <p>🔴 <b>「일정 물어보기」를 누를 때마다 다시 묻는다.</b> 문구만 바뀐다. 이 상태에만
	 * 행동이 붙어 있고, 그것이 {@link #NEVER} 와 갈리는 유일한 자리다.
	 */
	LATER,

	/** 「다시 묻지 않기」 — 값이 없다. 더 안 묻고, 마이페이지에서만 고친다. */
	NEVER
}
