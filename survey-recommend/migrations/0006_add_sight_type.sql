-- S15P21E201-754 — 장소 유형에 「관광 · 명소 · 경치」(SIGHT)를 더한다 (일곱 → 여덟)
--
-- 🔴 이 파일은 자동으로 안 돈다. schema.sql 은 postgres 볼륨이 "처음
--    비어 있을 때"만 돈다(docker-entrypoint-initdb.d). 이미 떠 있는 설문
--    서버는 볼륨이 안 비어 있으니 schema.sql 을 다시 고쳐도 반영이 안 된다 —
--    그래서 이 ALTER 문을 손으로(또는 배포 스크립트로) 한 번 돌려야 한다.
--
-- 실행 (0002 · 0003 · 0004 · 0005 를 먼저 돌린 뒤):
--   docker exec -i survey-postgres psql -U survey -d survey \
--     < survey-recommend/migrations/0006_add_sight_type.sql
--
-- ── 왜 유형이 하나 더 필요한가 ────────────────────────────────────
-- 일곱 유형에는 **"보러 가는 곳" 을 담을 자리가 없었다.** 해운대해수욕장 ·
-- 감천문화마을 · 황령산 전망대 · 광안대교 야경 같은 곳이 그렇다.
--   - 해운대해수욕장 → 바다니까 NATURE? 부산에서 가장 유명한 관광지인데?
--   - 감천문화마을   → 마을이니까 CULTURE? 벽화 보러 가는 곳인데?
--   - 광안리 야경    → NATURE 도 CULTURE 도 아니다. 갈 곳이 없다
-- 적는 사람마다 다른 칸을 고르면 **같은 곳이 표에서 두세 유형으로 흩어진다.**
-- 그러면 "부산에서 관광지로 많이 추천된 곳" 을 셀 수가 없다 — 유형별로 세는
-- 순간 같은 장소가 갈라져 버려서, 어느 쪽도 실제 추천 수를 안 보여 준다.
-- 나중에 합칠 수도 없다. 어느 행이 "관광지로 적은 것" 이었는지가 안 남는다.
--
-- ── 🔴 왜 코드값이 SIGHT 인가 ─────────────────────────────────────
-- sight = "볼거리 · 명소". sightseeing(관광)의 그 sight 다. 이 갈래가 담는
-- 것이 정확히 그것이다 — **보러 가는 곳**(관광지 · 명소 · 전망 · 야경).
-- 다른 후보를 버린 이유:
--   TOUR     여행 전체를 가리켜 너무 넓다. 이 설문은 전부 "여행" 이야기다
--   VIEW     경치만 가리킨다. 감천문화마을 같은 명소가 안 들어간다
--   SCENIC   형용사라 나머지(FOOD · CAFE …)와 품사가 어긋난다
--   LANDMARK 랜드마크(대표 건물)만 가리킨다. 전망 · 야경이 안 들어간다
-- 기존 일곱과 같은 모양으로 맞췄다: 대문자 ASCII 한 낱말.
--
-- ── 🔴 왜 IF NOT EXISTS 로 안 되고 DROP 후 다시 만드나 ───────────
-- 0005 가 이미 겪은 함정이다. `recommendation_place_type_ok` 라는 **이름은
-- 이미 있고 내용(일곱 값)이 좁다.** `ADD CONSTRAINT IF NOT EXISTS` 식으로
-- 쓰면 이름이 있으니 그냥 건너뛰고 **제약은 영영 안 넓어진다.** 그러면 새
-- 코드값이 들어올 때 DB 가 거절하는데, 마이그레이션은 성공했다고 나온다.
-- 조용히 아무 일도 안 하는 마이그레이션이 가장 나쁘다.
-- 그래서 지우고 다시 만든다. DROP ... IF EXISTS 라 두 번 돌려도 안 깨진다.
--
-- 🔴 넓히는 방향이라 **기존 행은 하나도 안 깨진다.** 일곱 값은 여덟 값 안에
--    있다. (좁히는 마이그레이션이었다면 이렇게 못 한다 — 그때는 옛 행을 먼저
--    옮겨야 하고, ADD CONSTRAINT 가 표 전체를 검사하다 그 자리에서 실패한다.)
--
-- 🔴 옛 응답의 유형을 **다시 나누지 않는다.** 이미 NATURE 로 들어온 해운대는
--    NATURE 로 남는다. 무엇을 보고 그렇게 적었는지 우리가 모르기 때문이다 —
--    추측으로 옮기면 그때부터 그 행은 응답이 아니라 우리 판단이 된다.
--    가르는 기준은 form_version 이다: 6 이상이면 SIGHT 를 고를 수 있었던
--    판이고, 그보다 낮으면 그 갈래가 아예 없었다.

BEGIN;

-- 받아들이는 유형에 'SIGHT' 하나만 더한다. 그 밖에는 한 글자도 안 바뀐다.
-- 🔴 순서까지 schema.sql 과 한 글자도 다르지 않게 맞춘다 (SIGHT 가 맨 앞이다 —
--    화면의 갈래 순서와 같다). 둘이 다르면 새로 띄운 DB 와 살아 있는 DB 가
--    서로 다른 표가 되고, 그건 두 DB 의 응답을 합치려는 날에야 드러난다.
ALTER TABLE recommendation DROP CONSTRAINT IF EXISTS recommendation_place_type_ok;
ALTER TABLE recommendation ADD  CONSTRAINT recommendation_place_type_ok
  CHECK (place_type IN (
    'SIGHT', 'FOOD', 'CAFE', 'NATURE', 'CULTURE', 'MARKET', 'ACTIVITY', 'BAR'));

-- 🔴 recommendation_slot_ok (1~10) 는 **안 건드린다.** 갈래가 여덟이 돼도
--    한 응답이 낼 수 있는 곳은 여전히 5~10 이다. 갈래마다 상한을 두지
--    않으므로(맛집만 열 곳도 받는다) 칸 번호의 상한도 그대로다.
-- 🔴 recommendation_one_per_slot (UNIQUE (response_id, slot)) 도 그대로다.
-- 🔴 UNIQUE (response_id, place_type) 은 **되살리지 않는다.** 갈래별 아코디언은
--    한 갈래에 여러 곳을 적으라고 만든 화면이다. 그 제약이 있으면 화면이
--    아무리 허용해도 DB 가 두 번째 맛집을 거절한다.

-- 🔴 form_version 은 0002 가 이미 만들었다. 여기서는 칸을 더하지 않고
--    **뜻만 하나 늘어난다**:
--      NULL 또는 1 = 이 칸이 생기기 전 판 (추천 다섯 곳 · 전화번호 · 가게 자동완성)
--      2           = 개인화 세 문항이 붙은 판
--      3           = 짝 비교까지 붙은 판
--      4           = 북적임 문항까지 붙은 판
--      5           = 장소 칸을 열까지 늘릴 수 있는 판
--      6           = **갈래 여덟 · 갈래마다 여러 곳을 적는 판** (이 파일)
--    안 올리면 나중에 반드시 이렇게 잘못 읽는다: "SIGHT 로 적힌 곳이 하나도
--    없네 → 사람들이 관광지를 안 추천하는구나". 사실은 그 갈래가 생기기
--    **전에** 들어온 응답이라 고를 수가 없었다.
--    숫자를 올리는 것은 server.mjs 의 FORM_VERSION 이다.

COMMIT;
