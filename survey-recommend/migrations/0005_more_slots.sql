-- S15P21E201-754 — 추천 장소 칸을 다섯에서 **열까지** 늘린다
--
-- 🔴 이 파일은 자동으로 안 돈다. schema.sql 은 postgres 볼륨이 "처음
--    비어 있을 때"만 돈다(docker-entrypoint-initdb.d). 이미 떠 있는 설문
--    서버는 볼륨이 안 비어 있으니 schema.sql 을 다시 고쳐도 반영이 안 된다 —
--    그래서 이 ALTER 문을 손으로(또는 배포 스크립트로) 한 번 돌려야 한다.
--
-- 실행 (0002 · 0003 · 0004 를 먼저 돌린 뒤):
--   docker exec -i survey-postgres psql -U survey -d survey \
--     < survey-recommend/migrations/0005_more_slots.sql
--
-- ── 왜 늘리나 ────────────────────────────────────────────────────
-- 다섯으로 못 박아 두면 **부산을 가장 잘 아는 사람의 답이 잘려나간다.** 열 곳을
-- 아는 사람이 다섯 곳만 적고 나가는 것은 우리가 가장 원하는 응답을 절반 버리는
-- 것이다. 같은 유형(FOOD)이 다섯 번 와도 받기로 한 것과 똑같은 이유다.
--
-- 🔴 기본은 여전히 다섯이다. 화면은 다섯 칸으로 시작하고, 「한 곳 더 적기」를
--    누른 사람만 칸이 는다. 처음부터 열 칸을 보여 주면 그 길이 자체가
--    "열 곳을 적어야 하는구나" 로 읽혀 이탈을 만든다.
--
-- ── 🔴 왜 상한이 열인가 (무한이 아니라) ──────────────────────────
-- 상한이 없으면 화면 · DB · 검증이 전부 열린다: 한 번에 몇 줄이 들어올지 모르니
-- 요청 크기 상한(server.mjs 의 32KB)과 트랜잭션 하나의 INSERT 개수가 사람이
-- 아니라 보내는 쪽에 의해 정해진다. 열이면 다섯 곳을 아는 사람도, 열 곳을 아는
-- 사람도 담기고, 상한이 숫자로 남아 화면 · 서버 · DB 셋이 같은 값을 본다.
--    화면: index.html 의 MAX_SLOTS
--    서버: server.mjs 의 MAX_SLOTS
--    DB  : 아래 recommendation_slot_ok
-- 🔴 셋이 어긋나면 사람은 화면에서 통과하고 서버나 DB 에서 거절당한다.
--
-- ── 🔴 왜 IF NOT EXISTS 로 안 되고 DROP 후 다시 만드나 ───────────
-- 0004 는 **없는 제약을 새로 만드는** 일이라 pg_constraint 에 이름이 있으면
-- 건너뛰면 됐다. 여기는 다르다 — `recommendation_slot_ok` 라는 **이름은 이미
-- 있고 내용(1~5)이 좁다.** 같은 방식으로 쓰면 이름이 있으니 그냥 건너뛰고
-- 제약은 영영 안 넓어진다. 조용히 아무 일도 안 하는 마이그레이션이 가장 나쁘다.
-- 그래서 지우고 다시 만든다. DROP ... IF EXISTS 라 두 번 돌려도 안 깨진다.
--
-- 🔴 넓히는 방향이라 **기존 행은 하나도 안 깨진다.** 1~5 는 1~10 안에 있다.
--    (좁히는 마이그레이션이었다면 이렇게 못 한다 — 그때는 옛 행을 먼저 옮겨야
--     하고, ADD CONSTRAINT 가 표 전체를 검사하다 그 자리에서 실패한다.)

BEGIN;

-- 칸 번호의 상한만 5 → 10 으로 넓힌다. 그 밖에는 한 글자도 안 바뀐다.
-- 🔴 이름과 내용을 schema.sql 과 한 글자도 다르지 않게 맞춘다. 둘이 다르면
--    새로 띄운 DB 와 살아 있는 DB 가 서로 다른 표가 된다.
ALTER TABLE recommendation DROP CONSTRAINT IF EXISTS recommendation_slot_ok;
ALTER TABLE recommendation ADD  CONSTRAINT recommendation_slot_ok
  CHECK (slot BETWEEN 1 AND 10);

-- 🔴 recommendation_one_per_slot (UNIQUE (response_id, slot)) 은 **안 건드린다.**
--    한 응답 안에서 칸 번호가 안 겹친다는 규칙은 칸이 열이 돼도 그대로다.
--    (1~5 가 한 번씩 → 1~n 이 한 번씩. 제약 자체는 개수를 안 센다.)

-- 🔴 form_version 은 0002 가 이미 만들었다. 여기서는 칸을 더하지 않고
--    **뜻만 하나 늘어난다**:
--      NULL 또는 1 = 이 칸이 생기기 전 판 (추천 다섯 곳 · 전화번호 · 가게 자동완성)
--      2           = 개인화 세 문항이 붙은 판
--      3           = 짝 비교까지 붙은 판
--      4           = 북적임 문항까지 붙은 판
--      5           = **장소 칸을 열까지 늘릴 수 있는 판** (이 파일)
--    안 올리면 나중에 반드시 이렇게 잘못 읽는다: "응답 100건 중 여섯 칸 이상을
--    적은 사람이 3건뿐이네 → 3% 만 더 적고 싶어 했다". 사실은 97건이 그 버튼이
--    생기기 **전에** 들어온 것이라 더 적고 싶어도 못 적었다.
--    숫자를 올리는 것은 server.mjs 의 FORM_VERSION 이다.

COMMIT;
